namespace Minecraft.Domain.Entities.Mobs
{
    /// <summary>
    /// Danh mục phân loại các giống loài sinh vật (Mob) trong thế giới Voxel.
    /// </summary>
    public enum MobType
    {
        /// <summary>Thây ma (Mob thù địch cận chiến).</summary>
        Zombie = 0,

        /// <summary>Bò sữa (Mob hiền lành cung cấp tài nguyên).</summary>
        Cow = 1,

        /// <summary>Bộ xương (Mob thù địch tầm xa - Bài mở rộng thi vấn đáp).</summary>
        Skeleton = 2
    }
}
